-- این فایل را یک بار در Supabase > SQL Editor اجرا کنید.
create table if not exists public.product_discounts (
  id bigint generated by default as identity primary key,
  product_id text not null unique,
  code text not null unique,
  discount_type text not null check (discount_type in ('percent', 'fixed')),
  discount_value numeric(12,2) not null check (discount_value > 0),
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint product_discounts_percent_range check (discount_type <> 'percent' or discount_value <= 100)
);

alter table public.product_discounts enable row level security;

-- خواندن کدهای فعال برای اعتبارسنجی در فروشگاه؛ نوشتن فقط با دسترسی مجاز.
